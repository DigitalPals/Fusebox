#!/usr/bin/env python3
"""Compare asset build scripts and verify incremental invalidation, without servers."""
import argparse
import gzip
import hashlib
import json
import os
from pathlib import Path
import shutil
import statistics
import subprocess
import tempfile
import time


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--baseline-ref', default='f49466b')
    parser.add_argument('--output', type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    deps = root / 'target/release/deps'
    libraries = {name: max(deps.glob(f'lib{name}-*.rlib'), key=lambda p: p.stat().st_mtime)
                 for name in ('flate2', 'sha2')}
    with tempfile.TemporaryDirectory(prefix='fusebox-asset-bench-') as directory:
        work = Path(directory)
        shutil.copytree(root / 'ui', work / 'ui')
        env = dict(os.environ, CARGO_PKG_VERSION='benchmark', FUSEBOX_COMMIT='benchmark')
        timings = {}
        outputs = {}
        for name, source in [
            ('before', subprocess.check_output(['git', 'show', f'{args.baseline_ref}:build.rs'], cwd=root)),
            ('after', (root / 'build.rs').read_bytes()),
        ]:
            script = work / f'{name}.rs'
            script.write_bytes(source)
            binary = work / name
            command = ['rustup', 'run', 'stable', 'rustc', '--edition=2024', '-O', str(script),
                       '-L', f'dependency={deps}', '-o', str(binary)]
            for library, path in libraries.items():
                command.extend(['--extern', f'{library}={path}'])
            subprocess.run(command, cwd=root, check=True)
            out = work / f'{name}-out'
            out.mkdir()
            outputs[name] = out

            def run():
                started = time.perf_counter_ns()
                subprocess.run([str(binary)], cwd=work, env=dict(env, OUT_DIR=str(out)),
                               stdout=subprocess.DEVNULL, check=True)
                return (time.perf_counter_ns() - started) / 1e6

            run()  # Populate/warm the output directory; measure only reruns.
            timings[name] = [run() for _ in range(9)]

        before, after = outputs['before'], outputs['after']
        for path in before.iterdir():
            assert path.read_bytes() == (after / path.name).read_bytes(), path.name
        tracked = {p.name: p.stat().st_mtime_ns for p in after.iterdir()}
        run()
        assert tracked == {p.name: p.stat().st_mtime_ns for p in after.iterdir()}
        previous = {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in after.glob('*.gz')}
        # A dictionary edit must invalidate its loader and the index transitively.
        dictionary = work / 'ui/i18n-zh.js'
        dictionary.write_bytes(dictionary.read_bytes() + b'\n// incremental build verification\n')
        run()
        changed = sorted(p.name for p in after.glob('*.gz')
                         if hashlib.sha256(p.read_bytes()).hexdigest() != previous[p.name])
        assert changed == ['i18n-zh.js.gz', 'i18n.js.gz', 'index.html.gz'], changed
        for path in after.glob('*.gz'):
            gzip.decompress(path.read_bytes())
        # Missing generated bytes or an interrupted write without its validity
        # marker must be repaired, even when source content is unchanged.
        asset = after / 'app.js.gz'
        expected = asset.read_bytes()
        asset.unlink()
        run()
        assert asset.read_bytes() == expected
        (after / 'app.js.gz.fingerprint').unlink()
        asset.write_bytes(b'incomplete gzip')
        run()
        assert asset.read_bytes() == expected
        result = {
            'baseline_ref': args.baseline_ref,
            'methodology': 'Same UI fixture and optimized build-script compiler; nine warm no-change reruns per implementation. Includes process startup, hashing and file I/O; no full Cargo compilation.',
            'compiler': subprocess.check_output(['rustup', 'run', 'stable', 'rustc', '--version'], text=True).strip(),
            'before_ms': timings['before'], 'after_ms': timings['after'],
            'before_median_ms': statistics.median(timings['before']),
            'after_median_ms': statistics.median(timings['after']),
            'identical_initial_outputs': True, 'unchanged_output_mtimes_on_rerun': True,
            'transitive_invalidation_verified': changed,
            'missing_and_incomplete_outputs_recovered': True,
        }
    report = json.dumps(result, indent=2) + '\n'
    if args.output:
        args.output.write_text(report)
    print(report, end='')


if __name__ == '__main__':
    main()
